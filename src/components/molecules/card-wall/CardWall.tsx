import {
  GABBERG_CARDS,
  cardQrPath,
  cardUrl,
  type GabbergCard,
} from "@/data/gabberg-cards";
import Image from "next/image";
import styles from "./CardWall.module.scss";

interface CardWallProps {
  cards?: GabbergCard[];
}

/**
 * The printed cards, with their codes live enough to scan off the screen.
 *
 * The project's argument is that one deploy serves every persona and a new
 * variant is a new printed code rather than a new release. Listing the card
 * types would state that; showing the codes and letting a reader point a phone
 * at one demonstrates it.
 *
 * The codes are flat SVGs generated by `npm run qr`, not encoded in the
 * browser: they never change, and shipping a QR encoder to draw them would be
 * paying at runtime for something the repository already knows.
 */
export default function CardWall({ cards = GABBERG_CARDS }: CardWallProps) {
  if (!cards.length) return null;

  return (
    <section className={styles.wall} aria-label="The printed cards">
      <h3 className={styles.title}>The cards</h3>
      <p className={styles.lede}>
        One deploy behind all of them. Each printed code carries its own{" "}
        <code className={styles.code}>card_type</code>, so a new persona is a
        new card rather than a new release. Point a phone at one.
      </p>

      <ul className={styles.grid}>
        {cards.map((card) => (
          <li key={card.type} className={styles.card}>
            <a
              className={styles.qrLink}
              href={cardUrl(card)}
              target="_blank"
              rel="noreferrer"
            >
              <span className={styles.qrFrame}>
                <Image
                  src={cardQrPath(card)}
                  alt={`QR code opening the ${card.label} card`}
                  width={160}
                  height={160}
                  className={styles.qr}
                  unoptimized
                />
              </span>
              <span className={styles.label}>{card.label}</span>
            </a>
            {card.context && <p className={styles.context}>{card.context}</p>}
            <p className={styles.type}>{card.type}</p>
          </li>
        ))}
      </ul>
    </section>
  );
}
